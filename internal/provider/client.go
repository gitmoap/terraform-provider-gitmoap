// Client calls the gitmoap API. Configure gives it to every resource and data source.
type Client struct {
	endpoint  string
	token     string
	userAgent string
	http      *http.Client
}

func NewClient(endpoint, token, userAgent string) *Client {
	return &Client{
		endpoint:  strings.TrimRight(endpoint, "/"),
		token:     token,
		userAgent: userAgent,
		http:      &http.Client{Timeout: time.Minute},
	}
}

// APIError is a response with a status outside 2xx.
type APIError struct {
	Method     string
	Path       string
	StatusCode int
	Body       string
}

func (e *APIError) Error() string {
	detail := e.Body
	var parsed struct {
		Error struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}
	if json.Unmarshal([]byte(e.Body), &parsed) == nil && parsed.Error.Message != "" {
		detail = parsed.Error.Message + " (" + parsed.Error.Code + ")"
	}
	return fmt.Sprintf("%s %s: %d %s: %s", e.Method, e.Path, e.StatusCode, http.StatusText(e.StatusCode), detail)
}

// IsNotFound reports whether err is a 404 from the API.
func IsNotFound(err error) bool {
	var apiErr *APIError
	return errors.As(err, &apiErr) && apiErr.StatusCode == http.StatusNotFound
}

const maxAttempts = 5

// Do sends body as JSON, unless it's nil, and decodes the JSON response into out, unless it's nil.
// Numbers decode as json.Number, so large integers keep every digit. path is relative to the
// endpoint, with its parameters escaped. A 429, or a block by the CDN, is retried after a wait.
func (c *Client) Do(ctx context.Context, method, path string, query url.Values, body, out any) error {
	var payload []byte
	if body != nil {
		var err error
		if payload, err = json.Marshal(body); err != nil {
			return fmt.Errorf("encoding the request to %s %s: %w", method, path, err)
		}
	}
	target := c.endpoint + path
	if len(query) > 0 {
		target += "?" + query.Encode()
	}

	for attempt := 1; ; attempt++ {
		req, err := http.NewRequestWithContext(ctx, method, target, bytes.NewReader(payload))
		if err != nil {
			return err
		}
		req.Header.Set("Authorization", "Bearer "+c.token)
		req.Header.Set("Accept", "application/json")
		req.Header.Set("User-Agent", c.userAgent)
		if body != nil {
			req.Header.Set("Content-Type", "application/json")
		}
		tflog.Debug(ctx, "gitmoap API request", map[string]any{"method": method, "path": path, "query": query.Encode(), "body": string(payload)})

		resp, err := c.http.Do(req)
		if err != nil {
			return err
		}
		data, err := io.ReadAll(resp.Body)
		resp.Body.Close()
		if err != nil {
			return fmt.Errorf("reading the response to %s %s: %w", method, path, err)
		}
		tflog.Debug(ctx, "gitmoap API response", map[string]any{"method": method, "path": path, "status": resp.StatusCode, "body": string(data)})

		// The CDN in front of the API blocks a client that sends too much for a minute or two,
		// with a 403 of its own.
		blocked := resp.StatusCode == http.StatusForbidden && bytes.Contains(data, []byte("Generated by cloudfront"))
		if (resp.StatusCode == http.StatusTooManyRequests || blocked) && attempt < maxAttempts {
			wait := time.Duration(attempt) * 2 * time.Second
			if blocked {
				wait = time.Duration(min(attempt, 2)) * 30 * time.Second
			}
			if seconds, err := strconv.Atoi(resp.Header.Get("Retry-After")); err == nil {
				wait = time.Duration(seconds) * time.Second
			}
			tflog.Warn(ctx, "gitmoap API asked to slow down", map[string]any{"status": resp.StatusCode, "wait": wait.String()})
			select {
			case <-time.After(wait):
				continue
			case <-ctx.Done():
				return ctx.Err()
			}
		}
		if resp.StatusCode < 200 || resp.StatusCode > 299 {
			return &APIError{Method: method, Path: path, StatusCode: resp.StatusCode, Body: string(data)}
		}
		if out == nil || len(bytes.TrimSpace(data)) == 0 {
			return nil
		}
		decoder := json.NewDecoder(bytes.NewReader(data))
		decoder.UseNumber()
		if err := decoder.Decode(out); err != nil {
			return fmt.Errorf("decoding the response to %s %s: %w", method, path, err)
		}
		return nil
	}
}

// Get reads path. With pages, it reads every page and returns the first with all the items.
func (c *Client) Get(ctx context.Context, path string, query url.Values, pages *pages) (any, error) {
	if pages == nil {
		var out any
		err := c.Do(ctx, http.MethodGet, path, query, nil, &out)
		return out, err
	}
	query = cloneValues(query)
	if pages.Limit > 0 {
		query.Set("limit", strconv.FormatInt(pages.Limit, 10))
	}
	var first map[string]any
	var items []any
	for {
		var page map[string]any
		if err := c.Do(ctx, http.MethodGet, path, query, nil, &page); err != nil {
			return nil, err
		}
		if first == nil {
			first = page
		}
		pageItems, _ := page[pages.Items].([]any)
		items = append(items, pageItems...)
		next, _ := page["next_token"].(string)
		if next == "" || len(pageItems) == 0 {
			break
		}
		query.Set(pages.Param, next)
	}
	if first == nil {
		first = map[string]any{}
	}
	first[pages.Items] = items
	delete(first, "next_token")
	return first, nil
}

func cloneValues(values url.Values) url.Values {
	out := url.Values{}
	for key, value := range values {
		out[key] = append([]string(nil), value...)
	}
	return out
}

// clientFrom returns the client Configure set up, or nil when Terraform calls before configuring the
// provider, as it does to validate a configuration.
func clientFrom(providerData any, diags *diag.Diagnostics) *Client {
	if providerData == nil {
		return nil
	}
	client, ok := providerData.(*Client)
	if !ok {
		diags.AddError("Unexpected provider data", fmt.Sprintf("Expected *provider.Client, got %T. This is a bug in the provider.", providerData))
	}
	return client
}
