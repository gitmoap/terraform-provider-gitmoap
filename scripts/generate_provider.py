#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# ///
"""Generate the provider's Go code from provider_code_spec.json and provider_api.json.

    python3 scripts/generate_provider.py

Run it after scripts/generate_generator_config.py, or run both with `make generate`. In order:

  1. Deletes the generated packages under internal/provider (resource_*, datasource_*), so a
     resource that's gone from the API doesn't linger, and generates them again with
     tfplugingen-framework: each holds a resource's or data source's schema and model.
  2. Writes internal/provider/api_gen.go: the operations behind each resource and data source,
     from provider_api.json.
  3. Writes internal/provider/registry_gen.go, which gives each resource and data source to the
     shared implementation (rest_resource.go, rest_data_source.go) with its generated schema.
  4. Writes examples/resources/<type>/import.sh for each resource, from the attributes it's
     imported by, for the documentation. The other examples are written by hand.

What one resource needs beyond the shared implementation goes in an override, by hand: see
internal/provider/overrides.go.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PROVIDER_DIR = REPO_ROOT / "internal" / "provider"
CODE_SPEC = REPO_ROOT / "provider_code_spec.json"
API_MAP = REPO_ROOT / "provider_api.json"

# Generated package directories, by the tfplugingen-framework command that writes them.
GENERATED = {"resources": "resource_", "data-sources": "datasource_"}

HEADER = "// Code generated by scripts/generate_provider.py. DO NOT EDIT.\n\npackage provider\n"


def go_name(name: str) -> str:
    """tfplugingen-framework's FrameworkIdentifier.ToPascalCase, which names the generated code."""
    return re.sub(r"^[a-z]|_[a-z0-9]", lambda match: match.group(0).replace("_", "").upper(), name)


def module_path() -> str:
    match = re.search(r"^module\s+(\S+)", (REPO_ROOT / "go.mod").read_text(), re.MULTILINE)
    if not match:
        sys.exit("error: no module line in go.mod")
    return match.group(1)


def regenerate_packages() -> None:
    for directory in PROVIDER_DIR.glob("*_*"):
        generated = directory.is_dir() and directory.name.startswith(tuple(GENERATED.values()))
        if generated and all(file.name.endswith("_gen.go") for file in directory.iterdir()):
            shutil.rmtree(directory)
    for command in GENERATED:
        subprocess.run(
            ["go", "-C", str(REPO_ROOT), "tool", "tfplugingen-framework", "generate", command, "--input", str(CODE_SPEC), "--output", str(PROVIDER_DIR)],
            check=True,
        )


# Go literals. json.dumps writes strings Go reads the same way.


def go_string_map(values: dict[str, str]) -> str:
    return "map[string]string{" + ", ".join(f"{json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(values.items())) + "}"


def go_strings(values: list[str]) -> str:
    return "[]string{" + ", ".join(json.dumps(value) for value in values) + "}"


def go_operation(op: dict, pointer: bool = False) -> str:
    fields = [f"Method: {json.dumps(op['method'])}", f"Path: {json.dumps(op['path'])}"]
    if op.get("body"):
        fields.append(f"Body: {go_string_map(op['body'])}")
    if op.get("items"):
        fields.append(f"Items: {json.dumps(op['items'])}")
    if op.get("query"):
        fields.append(f"Query: {go_string_map(op['query'])}")
    if op.get("pages"):
        pages = op["pages"]
        fields.append(f"Pages: &pages{{Param: {json.dumps(pages['param'])}, Items: {json.dumps(pages['items'])}, Limit: {pages.get('limit', 0)}}}")
    return ("&" if pointer else "") + "operation{" + ", ".join(fields) + "}"


def go_resource_api(api: dict) -> str:
    fields = [f"Create: {go_operation(api['create'])}", f"Read: {go_operation(api['read'])}"]
    if "update" in api:
        fields.append(f"Update: {go_operation(api['update'], pointer=True)}")
    if "delete" in api:
        fields.append(f"Delete: {go_operation(api['delete'], pointer=True)}")
    fields.append(f"Params: {go_string_map(api['params'])}")
    fields.append(f"Identity: {go_strings(api['identity'])}")
    if "match" in api:
        fields.append(f"Match: {go_string_map(api['match'])}")
    if "replace" in api:
        fields.append(f"Replace: {go_strings(api['replace'])}")
    if "renames" in api:
        fields.append(f"Renames: {go_string_map(api['renames'])}")
    return "{\n" + "".join(f"\t\t{field},\n" for field in fields) + "\t}"


def go_data_source_api(api: dict) -> str:
    fields = [f"Read: {go_operation(api['read'])}", f"Params: {go_string_map(api['params'])}"]
    if "root" in api:
        fields.append(f"Root: {json.dumps(api['root'])}")
    if "renames" in api:
        fields.append(f"Renames: {go_string_map(api['renames'])}")
    return "{\n" + "".join(f"\t\t{field},\n" for field in fields) + "\t}"


def write_api(api_map: dict) -> Path:
    lines = [HEADER, "var resourceAPIs = map[string]resourceAPI{"]
    lines += [f"\t{json.dumps(name)}: {go_resource_api(api)}," for name, api in sorted(api_map["resources"].items())]
    lines += ["}", "", "var dataSourceAPIs = map[string]dataSourceAPI{"]
    lines += [f"\t{json.dumps(name)}: {go_data_source_api(api)}," for name, api in sorted(api_map["data_sources"].items())]
    lines += ["}", ""]
    path = PROVIDER_DIR / "api_gen.go"
    path.write_text("\n".join(lines))
    return path


def write_registry(resources: list[str], data_sources: list[str], module: str) -> Path:
    imports = [f'\t"{module}/internal/provider/resource_{name}"' for name in resources]
    imports += [f'\t"{module}/internal/provider/datasource_{name}"' for name in data_sources]
    lines = [
        HEADER,
        "import (",
        '\t"github.com/hashicorp/terraform-plugin-framework/datasource"',
        '\t"github.com/hashicorp/terraform-plugin-framework/resource"',
        "",
        *imports,
        ")",
        "",
        "func resources() []func() resource.Resource {",
        "\treturn []func() resource.Resource{",
        *(f"\t\tnewRestResource({json.dumps(name)}, resource_{name}.{go_name(name)}ResourceSchema)," for name in resources),
        "\t}",
        "}",
        "",
        "func dataSources() []func() datasource.DataSource {",
        "\treturn []func() datasource.DataSource{",
        *(f"\t\tnewRestDataSource({json.dumps(name)}, datasource_{name}.{go_name(name)}DataSourceSchema)," for name in data_sources),
        "\t}",
        "}",
        "",
    ]
    path = PROVIDER_DIR / "registry_gen.go"
    path.write_text("\n".join(lines))
    return path


def write_import_examples(api_map: dict) -> list[str]:
    """Write each resource's import example, and remove those of resources that are gone. Returns
    the example directories left with hand-written files for a resource that's gone."""
    examples = REPO_ROOT / "examples" / "resources"
    stale = []
    for directory in sorted(examples.glob("gitmoap_*")):
        if directory.name.removeprefix("gitmoap_") not in api_map["resources"]:
            (directory / "import.sh").unlink(missing_ok=True)
            if any(directory.iterdir()):
                stale.append(str(directory.relative_to(REPO_ROOT)))
            else:
                directory.rmdir()
    for name, api in sorted(api_map["resources"].items()):
        names = [attribute.rsplit(".", 1)[-1] for attribute in api["identity"]]
        how = f"its {names[0]}" if len(names) == 1 else f"its {', '.join(names[:-1])} and {names[-1]}, joined with slashes"
        directory = examples / f"gitmoap_{name}"
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "import.sh").write_text(
            f"# Import by {how}.\nterraform import gitmoap_{name}.example \"{'/'.join(f'<{n}>' for n in names)}\"\n"
        )
    return stale


def main() -> int:
    if not shutil.which("go"):
        sys.exit("error: go is not on PATH; it runs tfplugingen-framework at the version pinned in go.mod")
    code_spec = json.loads(CODE_SPEC.read_text())
    api_map = json.loads(API_MAP.read_text())
    resources = sorted(entry["name"] for entry in code_spec.get("resources", []))
    data_sources = sorted(entry["name"] for entry in code_spec.get("datasources", []))
    missing = sorted(set(resources) - set(api_map["resources"])) + sorted(set(data_sources) - set(api_map["data_sources"]))
    if missing:
        sys.exit(f"error: {API_MAP.name} has nothing for {', '.join(missing)}: run scripts/generate_generator_config.py first")

    PROVIDER_DIR.mkdir(parents=True, exist_ok=True)
    regenerate_packages()
    written = [write_api(api_map), write_registry(resources, data_sources, module_path())]
    subprocess.run(["gofmt", "-w", *map(str, written)], check=True)
    stale = write_import_examples(api_map)
    print(f"generated {len(resources)} resources and {len(data_sources)} data sources in {PROVIDER_DIR.relative_to(REPO_ROOT)}", file=sys.stderr)
    if stale:
        print(f"{len(stale)} problems to fix:", file=sys.stderr)
        for directory in stale:
            print(f"  {directory}: has examples for a resource that isn't generated any more. Fix: delete them", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
