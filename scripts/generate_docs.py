# The same argument on a group's data source and on a repository's.
SCOPED_VALUES = {
    "branch_rule_id": ("gitmoap_group_branch_rule.main.branch_rule_id", "gitmoap_repository_branch_rule.main.branch_rule_id"),
    "tag_rule_id": ("gitmoap_group_tag_rule.releases.tag_rule_id", "gitmoap_repository_tag_rule.releases.tag_rule_id"),
    "milestone_id": ("gitmoap_group_milestone.launch.milestone_id", "gitmoap_repository_milestone.v2.milestone_id"),
    "webhook_id": ("gitmoap_group_webhook.chat.webhook_id", "gitmoap_repository_webhook.ci.webhook_id"),
}

# Arguments whose value depends on the data source.
NAMED_VALUES = {
    ("group_by_path", "full_path"): '"acme"',
    ("repository_by_path", "full_path"): '"acme/platform/api"',
    ("group_wiki_page", "path"): '"home"',
    ("repository_wiki_page", "path"): '"home"',
    ("repository_catalog_resolve", "path"): '["services/payments/handler.go"]',
}


def value_for(data_source: str, argument: str) -> str:
    if (data_source, argument) in NAMED_VALUES:
        return NAMED_VALUES[(data_source, argument)]
    if argument in SCOPED_VALUES:
        group, repository = SCOPED_VALUES[argument]
        return repository if data_source.startswith("repository_") else group
    if argument in VALUES:
        return VALUES[argument]
    return f"var.{argument if argument.endswith('_id') else data_source + '_' + argument}"


def data_source_example(name: str, required: list[str]) -> str:
    label = "acme" if "group_id" in required else "api" if {"repo_id", "repository_id"} & set(required) else "example"
    width = max((len(argument) for argument in required), default=0)
    lines = [f'data "gitmoap_{name}" "{label}" {{']
    lines += [f"  {argument.ljust(width)} = {value_for(name, argument)}" for argument in required]
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_data_source_examples(code_spec: dict) -> tuple[int, list[str]]:
    data_sources = {entry["name"]: entry for entry in code_spec.get("datasources", [])}
    written = 0
    for name, entry in sorted(data_sources.items()):
        path = EXAMPLES / "data-sources" / f"gitmoap_{name}" / "data-source.tf"
        if path.exists():
            continue
        required = sorted(
            attribute["name"]
            for attribute in entry["schema"]["attributes"]
            if attribute[next(key for key in attribute if key != "name")].get("computed_optional_required") == "required"
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data_source_example(name, required))
        written += 1
    stale = [
        str(directory.relative_to(REPO_ROOT))
        for directory in sorted((EXAMPLES / "data-sources").glob("gitmoap_*"))
        if directory.name.removeprefix("gitmoap_") not in data_sources
    ]
    return written, stale


BLOCK = re.compile(r'^(resource|data|variable) "([\w-]+)"(?: "([\w-]+)")? \{', re.MULTILINE)
DATA_REFERENCE = re.compile(r"\bdata\.(gitmoap_[a-z0-9_]+)\.([a-z0-9_]+)")
RESOURCE_REFERENCE = re.compile(r"(?<![\w.])(gitmoap_[a-z0-9_]+)\.([a-z0-9_]+)")
VARIABLE_REFERENCE = re.compile(r"\bvar\.([a-z0-9_]+)")
SECRET = re.compile(r"secret|password|token|key")


def address(kind: str, first: str, second: str | None) -> str:
    return {"resource": f"{first}.{second}", "data": f"data.{first}.{second}", "variable": f"var.{first}"}[kind]


def blocks(text: str) -> dict[str, str]:
    """The top-level blocks of a formatted file, by address, in order."""
    found = {}
    for match in BLOCK.finditer(text):
        end = text.index("\n}", match.start()) + 2
        found[address(*match.groups())] = text[match.start():end]
    return found


def references(text: str) -> set[str]:
    code = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
    found = {f"data.{kind}.{name}" for kind, name in DATA_REFERENCE.findall(code)}
    found |= {f"{kind}.{name}" for kind, name in RESOURCE_REFERENCE.findall(code)}
    found |= {f"var.{name}" for name in VARIABLE_REFERENCE.findall(code)}
    return found


def variable_block(name: str) -> str:
    if SECRET.search(name):
        return f'variable "{name}" {{\n  type      = string\n  sensitive = true\n}}'
    return f'variable "{name}" {{\n  type = string\n}}'


def complete_examples() -> tuple[int, list[str]]:
    """Add what each example refers to but doesn't define. Returns how many changed, and the
    references nothing defines."""
    library = blocks((EXAMPLES / "shared.tf").read_text())
    order = list(library)
    changed, unknown = 0, []
    paths = sorted(EXAMPLES.glob("resources/*/resource*.tf")) + sorted(EXAMPLES.glob("data-sources/*/data-source*.tf"))
    paths += sorted(EXAMPLES.glob("ephemeral-resources/*/ephemeral-resource*.tf"))
    for path in paths:
        text = path.read_text()
        have = set(blocks(text))
        needed, queue = set(), sorted(references(text) - have)
        while queue:
            reference = queue.pop()
            if reference in have or reference in needed:
                continue
            if reference in library:
                needed.add(reference)
                queue += sorted(references(library[reference]))
            elif reference.startswith("var."):
                needed.add(reference)
            else:
                unknown.append(f"{path.relative_to(REPO_ROOT)}: refers to {reference}, which neither it nor examples/shared.tf defines")
        if not needed:
            continue
        variables = [variable_block(reference.removeprefix("var.")) for reference in sorted(needed) if reference.startswith("var.") and reference not in library]
        definitions = [library[reference] for reference in order if reference in needed]
        path.write_text("\n\n".join(variables + definitions) + "\n\n" + text)
        changed += 1
    return changed, unknown


def scenarios() -> list[dict]:
    found = []
    for directory in sorted((EXAMPLES / "scenarios").iterdir()):
        readme = (directory / "README.md").read_text().strip()
        title, _, description = readme.partition("\n")
        code = "\n".join(path.read_text() for path in sorted(directory.rglob("*.tf")))
        found.append({
            "title": title.removeprefix("# ").strip(),
            "description": description.strip(),
            "main": (directory / "main.tf").relative_to(REPO_ROOT).as_posix(),
            "resources": set(re.findall(r'^resource "gitmoap_([a-z0-9_]+)"', code, re.MULTILINE)),
            "data_sources": set(re.findall(r'^data "gitmoap_([a-z0-9_]+)"', code, re.MULTILINE)),
            "ephemeral_resources": set(re.findall(r'^ephemeral "gitmoap_([a-z0-9_]+)"', code, re.MULTILINE)),
        })
    return found


IMPORT_SECTION = """
{{- if .HasImport }}

## Import

Import is supported using the following syntax:

The [`terraform import` command](https://developer.hashicorp.com/terraform/cli/commands/import) can be used, for example:

{{codefile "shell" .ImportFile }}
{{- end }}
"""


def template(used_by: list[dict], is_resource: bool) -> str:
    parts = [
        GENERATED,
        "---",
        'page_title: "{{.Name}} {{.Type}} - {{.RenderedProviderName}}"',
        'subcategory: ""',
        "description: |-",
        '{{ .Description | plainmarkdown | trimspace | prefixlines "  " }}',
        "---",
        "",
        "# {{.Name}} ({{.Type}})",
        "",
        "{{ .Description | trimspace }}",
        "",
        "## Example Usage",
        "{{- if .HasExample }}",
        "",
        "### Basic Usage",
        "",
        "{{ tffile .ExampleFile }}",
        "{{- end }}",
    ]
    for scenario in used_by:
        parts += ["", f"### {scenario['title']}", "", scenario["description"], "", f'{{{{ tffile "{scenario["main"]}" }}}}']
    parts += ["", "{{ .SchemaMarkdown | trimspace }}"]
    text = "\n".join(parts)
    return text + (IMPORT_SECTION if is_resource else "\n")


def write_templates(found: list[dict]) -> int:
    wanted: dict[Path, str] = {}
    for kind, key, is_resource in (("resources", "resources", True), ("data-sources", "data_sources", False), ("ephemeral-resources", "ephemeral_resources", False)):
        names = sorted({name for scenario in found for name in scenario[key]})
        for name in names:
            used_by = sorted((scenario for scenario in found if name in scenario[key]), key=lambda scenario: scenario["title"])
            wanted[TEMPLATES / kind / f"{name}.md.tmpl"] = template(used_by, is_resource)
    for kind in ("resources", "data-sources", "ephemeral-resources"):
        for path in (TEMPLATES / kind).glob("*.md.tmpl"):
            if path not in wanted and path.read_text().startswith(GENERATED):
                path.unlink()
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return len(wanted)


def main() -> int:
    code_spec = json.loads(CODE_SPEC.read_text())
    written, stale = write_data_source_examples(code_spec)
    completed, unknown = complete_examples()
    found = scenarios()
    templates = write_templates(found)
    print(
        f"wrote {written} new data source examples, completed {completed} examples with what they refer to, "
        f"and wrote {templates} templates for the pages {len(found)} scenarios appear on",
        file=sys.stderr,
    )
    problems = [f"{directory}: has examples for a data source that isn't generated any more. Fix: delete them" for directory in stale]
    problems += unknown
    if problems:
        print(f"{len(problems)} problems to fix:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
