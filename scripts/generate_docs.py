#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# ///
"""Prepare the documentation's examples and templates, for tfplugindocs to render.

    python3 scripts/generate_docs.py

`make docs` runs it, then tfplugindocs. In order:

  1. Writes examples/data-sources/<type>/data-source.tf for each data source that has no example
     yet, filling its required arguments with the objects examples/shared.tf defines, or plain
     values. An example is written once: edit it freely afterwards.
  2. Completes each resource and data source example: when it refers to an object it doesn't
     define, adds the object's definition from examples/shared.tf to the top of the example, with
     whatever that one refers to in turn, and declares the variables it uses. So every example
     stands on its own, and can be copied as it is.
  3. Writes a template, templates/resources/<type>.md.tmpl or templates/data-sources/<type>.md.tmpl,
     for each resource and data source a scenario uses. Its page shows its own example, then each
     scenario: examples/scenarios/<name>/README.md gives the scenario's title and what it shows,
     and main.tf its configuration. Templates no scenario needs any more are removed.

A data source example left behind by a data source that's gone is reported, and so is an example
that refers to an object neither it nor examples/shared.tf defines. The script exits with 1 then.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = REPO_ROOT / "examples"
TEMPLATES = REPO_ROOT / "templates"
CODE_SPEC = REPO_ROOT / "provider_code_spec.json"

GENERATED = "{{/* Generated by scripts/generate_docs.py from examples/scenarios: edit those instead. */ -}}"

